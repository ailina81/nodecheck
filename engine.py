@dataclass
class Finding:
    severity: str          # "critical" | "warning"
    title: str
    explanation: str
    norm: str = ""
    item: str = ""         # к какой позиции спецификации относится
    fix_key: str = ""      # ключ в ALTERNATIVES


@dataclass
class AuditResult:
    status: str                                  # "ok" | "conflicts"
    findings: list = field(default_factory=list)
    recognized: list = field(default_factory=list)
    unknown: list = field(default_factory=list)

    def to_dict(self):
        return dict(status=self.status, findings=[asdict(f) for f in self.findings],
                    recognized=self.recognized, unknown=self.unknown)


# ---------------------------------------------------------------------------
# 2. Распознавание материалов из свободного текста
# ---------------------------------------------------------------------------
def _norm(s: str) -> str:
    return (s or "").lower().replace("ё", "е")


def recognize(text: str):
    """Возвращает id материала по ключевым словам (первое совпадение по порядку словаря)."""
    t = _norm(text)
    for mid, m in MATERIALS.items():
        for kw in m["kw"]:
            parts = _norm(kw).split()
            if all(p in t for p in parts):
                return mid
    return None


