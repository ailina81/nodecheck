_SURF_CODE = {"Пол": "F", "Стены": "W", "Потолок": "C", "Зона душа / прямой контакт с водой": "S"}
PRICE_LABEL = {1: "₸", 2: "₸₸", 3: "₸₸₸", 4: "₸₸₸₸", 5: "₸₸₸₸₸"}


def cheaper_analogs(room: str, ufh: str, rows: list[dict]):
    """Для каждой позиции ищет материалы дешевле, которые проходят ту же проверку без критичных ошибок."""
    out = []
    for r in rows:
        surf, raw = r.get("Поверхность", ""), r.get("Материал", "")
        mid = recognize(raw)
        code = _SURF_CODE.get(surf)
        if not mid or not code:
            continue
        cur = MATERIALS[mid]
        cands = []
        for cid, c in MATERIALS.items():
            if cid == mid or code not in c["surf"].split() or not (0 < c["price"] < cur["price"]):
                continue
            check = audit(room, ufh, [{"Поверхность": surf, "Материал": c["kw"][0]}])
            if any(f.severity == "critical" for f in check.findings):
                continue
            cands.append((c["price"], c["name"]))
        if cands:
            cands.sort(reverse=True)  # ближайшие по уровню цены — первыми (меньше потеря качества)
            out.append(dict(item=f"{surf} — «{raw}»", current=f"{cur['name']} ({PRICE_LABEL[cur['price']]})",
                            options=[f"{n} ({PRICE_LABEL[p]})" for p, n in cands[:3]]))
    return out
