def audit(room: str, ufh: str, rows: list[dict]) -> AuditResult:
    """rows: [{"Поверхность": "Пол", "Материал": "ламинат 33 класс"}, ...]"""
    res = AuditResult(status="ok")
    items = []
    for r in rows:
        surf = (r.get("Поверхность") or "").strip()
        mat = (r.get("Материал") or "").strip()
        if not mat:
            continue
        mid = recognize(mat)
        if mid:
            items.append((surf, mid, mat))
            res.recognized.append(f"{surf}: {mat} → {MATERIALS[mid]['name']}")
        else:
            res.unknown.append(f"{surf}: {mat}")

    add = res.findings.append
    wet = room.startswith("Санузел")
    evac = room.startswith("Коридор")
    kids = room.startswith("Детская")
    kitchen = room.startswith("Кухня")
    has_ufh = ufh != "Нет"
    ids = {mid for _, mid, _ in items}

    for surf, mid, raw in items:
        m = MATERIALS[mid]
        label = f"{surf} — «{raw}»"

        # --- Пол + тёплый пол -------------------------------------------------
        if surf == "Пол" and has_ufh:
            if m["ufh"] is None:
                add(Finding("critical", f"{m['name']} несовместим с тёплым полом",
                            "Материал либо рассыхается и деформируется при нагреве (массив), "
                            "либо имеет высокое термосопротивление (ковролин, пробка) — пол не прогреется, "
                            "а система будет работать на перегреве.",
                            "Инструкции производителей покрытий; R покрытия ≤ 0,15 м²·К/Вт (EN 1264)",
                            label, "floor_ufh"))
            elif m["ufh"] <= 27:
                add(Finding("warning", f"{m['name']} на тёплом полу — нужны ограничения",
                            f"Допустимо только при маркировке «для тёплого пола», температуре поверхности "
                            f"не выше {m['ufh']} °C (термостат с датчиком пола) и тонкой подложке с низким "
                            f"термосопротивлением. Без этого — коробление замков и запах от нагрева.",
                            "Инструкция производителя покрытия; EN 1264 (системы ТП)", label, "floor_ufh"))
            if ufh.startswith("Плёночный") and mid == "tile":
                add(Finding("warning", "Плёночный ИК-пол под плиткой",
                            "Плёнку нельзя укладывать прямо под плиточный клей — нужен разделительный слой "
                            "(ГВЛ/стяжка) либо выбрать кабельный мат.",
                            "Инструкции производителей ИК-плёнок", label, "floor_ufh"))

        # --- Влагостойкость --------------------------------------------------
        if wet and surf == "Пол" and m["water"] < 2:
            add(Finding("critical", f"{m['name']} в мокрой зоне",
                        "Материал впитывает воду: разбухание, плесень под покрытием. "
                        "В санузле пол должен быть водостойким и с гидроизоляцией по основанию.",
                        "Требования к отделке помещений с влажным режимом (СП РК / СНиП по полам)",
                        label, "floor_wet"))
        if kitchen and surf == "Пол" and m["water"] == 0:
            add(Finding("warning", f"{m['name']} на кухне",
                        "Кухня — зона риска протечек и частой влажной уборки. Покрытие без защиты замков "
                        "быстро теряет вид у мойки и посудомойки.", "", label, "floor_wet"))
        if surf.startswith("Зона душа") and m["water"] < 2:
            add(Finding("critical", f"{m['name']} в зоне прямого контакта с водой",
                        "В зоне душа допустимы только водостойкие покрытия по сплошной гидроизоляции. "
                        "Краска, обои, ГКЛ без защиты разрушаются за 1–2 сезона.",
                        "Требования к отделке мокрых зон; инструкции производителей", label, "wall_wet"))
        if wet and surf in ("Стены", "Потолок") and m["water"] == 0:
            add(Finding("critical", f"{m['name']} в санузле",
                        "Невлагостойкий материал в помещении с влажным режимом — отслоение и плесень.",
                        "Требования к отделке помещений с влажным режимом", label,
                        "base_wet" if mid == "gkl" else "wall_splash"))
        if wet and mid == "gklv" and "waterproof" not in ids:
            add(Finding("warning", "ГКЛВ без гидроизоляции",
                        "ГКЛВ только влагостойкий, а не водостойкий: в зоне брызг и душа его обязательно "
                        "покрывают обмазочной гидроизоляцией с лентой в углах.",
                        "Инструкции производителей ГКЛ-систем", label, "base_wet"))

        # --- Пожарная безопасность путей эвакуации ---------------------------
        if evac and surf in EVAC_LIMIT and m["km"] > EVAC_LIMIT[surf]:
            key = {"Пол": "fire_floor", "Стены": "fire_wall", "Потолок": "fire_ceil"}[surf]
            add(Finding("critical", f"{m['name']}: класс КМ{m['km']} на пути эвакуации",
                        f"Для отделки {surf.lower()} путей эвакуации в общественных зданиях (в т.ч. общежитиях) "
                        f"требуется класс не хуже КМ{EVAC_LIMIT[surf]} (точно — по таблице норм для "
                        f"класса функциональной пожарной опасности и этажности). Материал горюч и выделяет "
                        f"токсичный дым.", "СП РК 2.02-101 «Пожарная безопасность зданий и сооружений»; "
                        "аналог РФ — ФЗ-123, табл. 28", label, key))
        if evac and mid == "stretch":
            add(Finding("warning", "Натяжной потолок на пути эвакуации",
                        "Допустим только с сертификатом пожарной безопасности на конкретное полотно "
                        "(часто КМ1–КМ2 по НГ-основанию). Без сертификата — замечание экспертизы.",
                        "СП РК 2.02-101", label, "fire_ceil"))

        # --- Детская ---------------------------------------------------------
        if kids and mid in ("wp_vinyl", "pvc_panel", "linoleum"):
            add(Finding("warning", f"{m['name']} в детской",
                        "Синтетические покрытия на ПВХ-основе могут выделять летучие вещества и не "
                        "«дышат». Для детской предпочтительны материалы с низкой эмиссией.",
                        "Санитарные требования к отделке жилых помещений", label, "kids"))

    # --- Правила по сочетаниям ----------------------------------------------
    floors = [mid for s, mid, _ in items if s == "Пол"]
    if "tile" in floors and has_ufh and "glue_elast" not in ids:
        add(Finding("warning", "Плитка на тёплом полу без эластичного клея",
                    "Обычный цементный клей не компенсирует температурные деформации — плитка "
                    "отходит и трескается. Нужен клей класса C2 S1 (деформируемый).",
                    "EN 12004 (классы плиточных клеев)", "Клей / основание", "glue"))
    if wet and any(mid in ("tile", "spc") for _, mid, _ in items) and "waterproof" not in ids:
        add(Finding("warning", "Не указана гидроизоляция в санузле",
                    "Под плиткой в мокрой зоне нужна обмазочная гидроизоляция с заведением на стены "
                    "(в душе — на всю высоту зоны брызг). Плитка и затирка сами воду не держат.",
                    "Требования к полам помещений с влажным режимом", "Клей / основание", "base_wet"))

    # дедупликация
    seen, uniq = set(), []
    for f in res.findings:
        k = (f.title, f.item)
        if k not in seen:
            seen.add(k)
            uniq.append(f)
    res.findings = sorted(uniq, key=lambda f: 0 if f.severity == "critical" else 1)
    res.status = "conflicts" if res.findings else "ok"
    return res


def alternatives_for(findings, budget: str):
    out, used = [], set()
    for f in findings:
        if f.fix_key and f.fix_key not in used and f.fix_key in ALTERNATIVES:
            used.add(f.fix_key)
            out.append(dict(replace=f.item, suggestion=ALTERNATIVES[f.fix_key][budget],
                            why=f.title))
    return out


